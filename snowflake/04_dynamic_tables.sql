-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT unit.ID AS ENTITY_ID, unit.NAME AS ENTITY_NAME,
       unit.REGION, unit.CATEGORY, unit.STATUS,
       COUNT(*) AS EVENT_COUNT, SUM(observation.UPSET_COUNT) AS UPSET_COUNT,
       SUM(observation.OPERATING_HOURS) AS OPERATING_HOURS,
       SUM(observation.PLANNED_HOURS) AS PLANNED_HOURS,
       SUM(observation.DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(observation.PM_DUE) AS PM_DUE, SUM(observation.PM_COMPLETED) AS PM_COMPLETED,
       SUM(observation.CHARGE_BBL) AS CHARGE_BBL,
       SUM(observation.PRODUCT_BBL) AS PRODUCT_BBL, SUM(observation.TARGET_PRODUCT_BBL) AS TARGET_PRODUCT_BBL,
       SUM(observation.ENERGY_GJ) AS ENERGY_GJ,
       100.0 * SUM(observation.PRODUCT_BBL) / NULLIF(SUM(observation.TARGET_PRODUCT_BBL), 0) AS YIELD_ATTAINMENT_PCT,
       SUM(observation.ENERGY_GJ) / NULLIF(SUM(observation.CHARGE_BBL), 0) AS ENERGY_GJ_PER_BBL,
       100.0 * SUM(observation.OPERATING_HOURS) / NULLIF(SUM(observation.PLANNED_HOURS), 0) AS UNIT_AVAILABILITY_PCT,
       100.0 * SUM(observation.PM_COMPLETED) / NULLIF(SUM(observation.PM_DUE), 0) AS PM_COMPLIANCE_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.UNIT_DAILY observation
JOIN RAW.UNITS unit ON unit.ID = observation.ENTITY_ID
GROUP BY unit.ID, unit.NAME, unit.REGION, unit.CATEGORY, unit.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(PRODUCT_BBL) AS PRODUCT_BBL, SUM(TARGET_PRODUCT_BBL) AS TARGET_PRODUCT_BBL,
       SUM(CHARGE_BBL) AS CHARGE_BBL, SUM(ENERGY_GJ) AS ENERGY_GJ,
       SUM(UPSET_COUNT) AS UPSET_COUNT,
       100.0 * SUM(PRODUCT_BBL) / NULLIF(SUM(TARGET_PRODUCT_BBL), 0) AS YIELD_ATTAINMENT_PCT
FROM RAW.UNIT_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.UPSET_CAUSES
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ROOT_CAUSE, SUM(UPSET_COUNT) AS UPSET_COUNT,
       SUM(DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(TARGET_PRODUCT_BBL) - SUM(PRODUCT_BBL) AS PRODUCT_SHORTFALL_BBL
FROM RAW.UNIT_DAILY
WHERE UPSET_COUNT > 0
GROUP BY ROOT_CAUSE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(PRODUCT_BBL) AS PRODUCT_BBL, SUM(TARGET_PRODUCT_BBL) AS TARGET_PRODUCT_BBL,
         SUM(CHARGE_BBL) AS CHARGE_BBL, SUM(ENERGY_GJ) AS ENERGY_GJ,
         SUM(UPSET_COUNT) AS UPSETS,
         SUM(OPERATING_HOURS) AS OPERATING_HOURS, SUM(PLANNED_HOURS) AS PLANNED_HOURS,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.UNIT_DAILY
), fleet AS (SELECT COUNT(*) AS UNIT_COUNT FROM RAW.UNITS),
spares AS (
  SELECT 100.0 * SUM(LEAST(ON_HAND_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT
  FROM RAW.CRITICAL_SPARES
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Yield Attainment' AS TITLE,
         100.0 * PRODUCT_BBL / NULLIF(TARGET_PRODUCT_BBL, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Process Upsets', UPSETS, '' FROM observations
  UNION ALL SELECT 3, 'Energy Intensity', ENERGY_GJ / NULLIF(CHARGE_BBL, 0), ' GJ/bbl' FROM observations
  UNION ALL SELECT 4, 'Charge Processed (bbl)', CHARGE_BBL, '' FROM observations
  UNION ALL SELECT 5, 'Unit Availability', 100.0 * OPERATING_HOURS / NULLIF(PLANNED_HOURS, 0), '%' FROM observations
  UNION ALL SELECT 6, 'Process Units Monitored', UNIT_COUNT, '' FROM fleet
  UNION ALL SELECT 7, 'Critical Spares Coverage', COVERAGE_PCT, '%' FROM spares
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.TITLE = 'Energy Intensity' THEN TRIM(TO_VARCHAR(metrics.VALUE_NUM, '990.000'))
                WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.UPSET_CAUSES SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
